"""Generate single-file Agentverse-hosted bundles.

Agentverse's Build tab takes ONE script, but PayResolve is split across
agents/ + core/. This flattens them deterministically:

    hosted_<name>.py = [future import] + core/*.py (dep order) + agents/<name>.py

Intra-project imports (``from core.…``, ``from .x``) and dotenv are stripped
because the names resolve from the blob and hosted injects env directly.

Rerun after EVERY source change, then re-paste into Agentverse:

    python scripts/build_hosted.py

Never hand-edit the generated bundles.
"""
from __future__ import annotations
import pathlib
import py_compile
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT

CORE_ORDER = [
    "schemas.py",
    "policy_rules.py",
    "security.py",
    "cases.py",
    "messages.py",
    "langchain_triage.py",
    "resolution.py",
]

BUNDLES = {
    "hosted_payresolve.py": ("agents/orchestrator.py", ["cards.py"]),
    "hosted_triage.py": ("agents/triage_agent.py", []),
    "hosted_policy.py": ("agents/policy_agent.py", []),
    "hosted_evidence.py": ("agents/evidence_agent.py", []),
}

_LOCAL_IMPORT_RE = re.compile(r"^(from\s+core[\.\s]|from\s+\.)")


def _transform(src: str) -> str:
    out = []
    for line in src.splitlines():
        s = line.strip()
        if s.startswith("from __future__"):
            continue
        if _LOCAL_IMPORT_RE.match(s):
            continue
        if s in {"from dotenv import load_dotenv", "load_dotenv()"}:
            continue  # hosted injects env; dotenv is not on the allow-list
        if s.startswith("load_dotenv()"):
            continue
        out.append(line)
    return "\n".join(out).rstrip() + "\n"


def build(name: str, agent_rel: str, extra_core: list[str]) -> pathlib.Path:
    parts = [
        '"""GENERATED by scripts/build_hosted.py - do not hand-edit."""',
        "from __future__ import annotations",
    ]
    for fname in CORE_ORDER + extra_core:
        parts.append(f"\n# ===== core/{fname} (flattened) =====")
        parts.append(_transform((ROOT / "core" / fname).read_text(encoding="utf-8")))
    parts.append(f"\n# ===== {agent_rel} (flattened) =====")
    parts.append(_transform((ROOT / agent_rel).read_text(encoding="utf-8")))
    text = "\n".join(parts)

    # Fail loudly on anything that would break hosted imports.
    for i, ln in enumerate(text.splitlines(), 1):
        s = ln.strip()
        if _LOCAL_IMPORT_RE.match(s) or "load_dotenv" in s or s.startswith("import core"):
            raise AssertionError(f"{name}:{i} unflattened import: {s}")
    assert len(text) < 500_000, f"{name} suspiciously large"

    out = OUT / name
    out.write_text(text, encoding="utf-8")
    py_compile.compile(str(out), doraise=True)
    return out


def main() -> None:
    for name, (agent_rel, extra) in BUNDLES.items():
        out = build(name, agent_rel, extra)
        print(f"wrote {out.name} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
